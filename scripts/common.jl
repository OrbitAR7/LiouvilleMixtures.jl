# Results
# -----------------------------------------------------------------------------

"""
    record!(id, title, body; seed, runtime)

Write `results/rows/<id>.md`: a heading, the markdown `body` (tables and figure
captions), and a provenance line. Then regenerate `results/summary.md`.
"""
function record!(id::AbstractString, title::AbstractString, body::AbstractString; seed, runtime)
    open(joinpath(ROWDIR, "$id.md"), "w") do io
        println(io, "## $id: $title\n")
        println(io, strip(body), "\n")
        println(io, "*", provenance(seed, runtime), "*\n")
    end
    write_summary()
end

function write_summary()
    rows = sort(filter(f -> endswith(f, ".md"), readdir(ROWDIR)))
    open(joinpath(ROOT, "results", "summary.md"), "w") do io
        println(io, "# Results\n")
        println(io, "Generated by the scripts in `scripts/` (`julia --project=scripts -t auto scripts/reproduce_all.jl`). Do not edit by hand.\n")
        for f in rows
            println(io, read(joinpath(ROWDIR, f), String))
        end
    end
end

