import Pkg

const ROOT = normpath(joinpath(@__DIR__, ".."))
const FIGDIR = joinpath(ROOT, "results", "figures")
const ROWDIR = joinpath(ROOT, "results", "rows")
mkpath(FIGDIR); mkpath(ROWDIR)

# -----------------------------------------------------------------------------
# Provenance
# -----------------------------------------------------------------------------

function git_commit()
    c = try readchomp(`git -C $ROOT rev-parse --short HEAD`) catch; "unknown" end
    # changes under results/ are the scripts' own output, so they don't count as dirty
    dirty = try !isempty(readchomp(`git -C $ROOT status --porcelain --untracked-files=no -- . ':!results'`)) catch; false end
    return dirty ? c * "+dirty" : c
end

function package_versions(names = ("LiouvilleMixtures", "OrbitalMechanics", "EstimationToolkit",
                                   "OrdinaryDiffEqVerner", "ForwardDiff", "CairoMakie"))
    deps = Pkg.dependencies()
    v = Dict(d.name => d for d in values(deps))
    parts = String[]
    for n in names
        haskey(v, n) || continue
        d = v[n]
        tag = d.version === nothing ? "" : string(d.version)
        d.git_revision !== nothing && (tag *= "@" * first(d.git_revision, 7))
        push!(parts, "$n $tag")
    end
    return join(parts, ", ")
end

provenance(seed, runtime) = @sprintf("commit %s; Julia %s, %d threads; %s; seed %s; run time %.0f s; %s",
                                     git_commit(), VERSION, Threads.nthreads(), package_versions(),
                                     string(seed), runtime, Dates.format(now(), "yyyy-mm-dd HH:MM"))

