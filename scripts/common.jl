# -----------------------------------------------------------------------------
# Negentropy along a trajectory
# -----------------------------------------------------------------------------

"""
    negentropy_series_gh(p, P0, ts; n = 5) -> Vector

Exact negentropy J(t) of N(x0, P0) at each time in `ts`, from an n⁶-point
Gauss-Hermite rule. Each node is propagated once, and the output is whitened by
the exact linear map at each time (I2 in whitened coordinates).
"""
function negentropy_series_gh(p::TestProblem, P0, ts; n = 5)
    Ξ, W = gauss_hermite_tensor(6, n)
    S0 = Matrix(cholesky(Symmetric(Matrix(P0))).L)
    clouds = propagate_samples(p.model, p.x0 .+ S0 * Ξ, ts)
    lin = propagate_tensors(p.model, p.x0, last(ts); order = 1, saveat = ts)
    return map(eachindex(ts)) do k
        H = S0 \ (symplectic_inverse(p.model, lin.Φ[k]) * (clouds[k] .- lin.x[k]))
        logdet_quadrature_cov(H, W) / 2
    end
end

"""
    negentropy_series_mc(p, P0, ts; N, seed, B) -> Vector{MCEstimate}

Monte Carlo negentropy at each time: the paired estimator in whitened
coordinates, with a bootstrap interval (B replicates, 95%).
"""
function negentropy_series_mc(p::TestProblem, P0, ts; N = 200_000, seed = 1, B = 200)
    S0 = Matrix(cholesky(Symmetric(Matrix(P0))).L)
    X0 = sample_gaussian(Xoshiro(seed), collect(p.x0), P0, N)
    Ξ = S0 \ (X0 .- p.x0)
    clouds = propagate_samples(p.model, X0, ts)
    lin = propagate_tensors(p.model, p.x0, last(ts); order = 1, saveat = ts)
    return map(eachindex(ts)) do k
        H = S0 \ (symplectic_inverse(p.model, lin.Φ[k]) * (clouds[k] .- lin.x[k]))
        negentropy_mc(Ξ, H, I(6); B, rng = Xoshiro(seed + k))
    end
end

"Irreversible part J_irr(t) = min over s ≥ t of J(s), up to the end of the series."
irreversible(J) = reverse(accumulate(min, reverse(J)))

"Prior with position σ = s·σr and velocity σ = s·σv on every axis."
scaled_prior(s, σr, σv) = Diagonal([fill((s * σr)^2, 3); fill((s * σv)^2, 3)])
