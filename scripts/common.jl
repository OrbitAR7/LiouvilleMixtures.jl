# Shared helpers for the experiment scripts. Run them from the repository root:
#
#   julia --project=scripts -t auto scripts/e1_reversibility.jl
#
# Each script writes its figures to results/figures/ (PDF and PNG) and its rows
# to results/rows/<id>.md, then regenerates results/summary.md from all rows.
# Nothing under results/ is edited by hand.

using LiouvilleMixtures
